package genrefreshcontracts

import (
	"bytes"
	"fmt"
	"go/format"
	"strconv"
)

const generatedGoPolicyHeader = `// Code generated by genrefreshcontracts; DO NOT EDIT.
//
// refresh-domain-contract.json is the source of truth. Regenerate with: go generate ./backend

package domain

`

// RenderGoPolicy generates the backend's typed, ordered refresh-domain policy table.
func RenderGoPolicy() ([]byte, error) {
	domains, err := loadContractDomains()
	if err != nil {
		return nil, err
	}
	var out bytes.Buffer
	out.WriteString(generatedGoPolicyHeader)
	renderGoPolicyTypes(&out)
	renderGoPolicyTable(&out, domains)
	formatted, err := format.Source(out.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated Go refresh policy: %w", err)
	}
	return formatted, nil
}

func renderGoPolicyTypes(out *bytes.Buffer) {
	out.WriteString(`type DomainCategory string

const (
	DomainCategorySystem    DomainCategory = "system"
	DomainCategoryCluster   DomainCategory = "cluster"
	DomainCategoryNamespace DomainCategory = "namespace"
)

type CachePolicy string

const (
	CachePolicySnapshotCache                 CachePolicy = "snapshot-cache"
	CachePolicySnapshotCacheWithMerge        CachePolicy = "snapshot-cache-with-merge"
	CachePolicySnapshotCacheBypass           CachePolicy = "snapshot-cache-bypass"
	CachePolicySnapshotCachePlusProviderCache CachePolicy = "snapshot-cache-plus-provider-cache"
	CachePolicyProviderCache                 CachePolicy = "provider-cache"
	CachePolicyExternalCatalogCache          CachePolicy = "external-catalog-cache"
	CachePolicyExternalCatalogCacheWithMerge CachePolicy = "external-catalog-cache-with-merge"
	CachePolicyStreamOnly                    CachePolicy = "stream-only"
)

type SourceClock string

const (
	SourceClockObject    SourceClock = "object"
	SourceClockMetric    SourceClock = "metric"
	SourceClockEvent     SourceClock = "event"
	SourceClockCatalog   SourceClock = "catalog"
	SourceClockAttention SourceClock = "attention"
)

type BackendRegistrationKind string

const (
	BackendRegistrationDirect     BackendRegistrationKind = "direct"
	BackendRegistrationList       BackendRegistrationKind = "list"
	BackendRegistrationListWatch  BackendRegistrationKind = "listWatch"
	BackendRegistrationStreamOnly BackendRegistrationKind = "streamOnly"
)

type BackendPermissionKind string

const (
	BackendPermissionRuntime        BackendPermissionKind = "runtime"
	BackendPermissionExempt         BackendPermissionKind = "exempt"
	BackendPermissionStreamSpecific BackendPermissionKind = "stream-specific"
)

type FrontendOrchestratorKind string

const (
	FrontendOrchestratorSnapshot            FrontendOrchestratorKind = "snapshot"
	FrontendOrchestratorDoorbellSnapshot    FrontendOrchestratorKind = "doorbell-snapshot"
	FrontendOrchestratorResourceStream      FrontendOrchestratorKind = "resource-stream"
	FrontendOrchestratorCatalogStream       FrontendOrchestratorKind = "catalog-stream"
	FrontendOrchestratorContainerLogsStream FrontendOrchestratorKind = "container-logs-stream"
)

type DiagnosticsStream string

const (
	DiagnosticsStreamNone          DiagnosticsStream = ""
	DiagnosticsStreamResources     DiagnosticsStream = "resources"
	DiagnosticsStreamContainerLogs DiagnosticsStream = "container-logs"
)

type BackendPolicy struct {
	Registration       BackendRegistrationKind
	Permission         BackendPermissionKind
	ResourceStream     bool
	BypassSingleflight bool
}

type FrontendTimingPolicy struct {
	Interval int
	Cooldown int
	Timeout  int
}

type FrontendPolicy struct {
	RefresherName     string
	Orchestrator      FrontendOrchestratorKind
	DiagnosticsStream DiagnosticsStream
	Timing            FrontendTimingPolicy
	Priority          int
	HasPriority       bool
	RegistrationOrder int
	Scheduled         bool
}

type DomainPolicy struct {
	Domain       string
	Category     DomainCategory
	CachePolicy  CachePolicy
	SourceClocks []SourceClock
	Backend      BackendPolicy
	Frontend     FrontendPolicy
}

`)
}

func renderGoPolicyTable(out *bytes.Buffer, domains []domainSpec) {
	out.WriteString("var authoredDomainPolicies = []DomainPolicy{\n")
	for _, domain := range domains {
		fmt.Fprintf(out, "{Domain: %s, Category: DomainCategory(%s), CachePolicy: CachePolicy(%s), ",
			strconv.Quote(domain.domain),
			strconv.Quote(domain.category),
			strconv.Quote(domain.cachePolicy),
		)
		out.WriteString("SourceClocks: []SourceClock{")
		for index, source := range domain.sourceClocks {
			if index > 0 {
				out.WriteString(", ")
			}
			fmt.Fprintf(out, "SourceClock(%s)", strconv.Quote(source))
		}
		out.WriteString("}, ")
		fmt.Fprintf(out, "Backend: BackendPolicy{Registration: BackendRegistrationKind(%s), Permission: BackendPermissionKind(%s), ResourceStream: %t, BypassSingleflight: %t}, ",
			strconv.Quote(domain.backendRegistration),
			strconv.Quote(domain.backendPermission),
			domain.backendResourceStream,
			domain.backendBypassSingleflight,
		)
		fmt.Fprintf(out, "Frontend: FrontendPolicy{RefresherName: %s, Orchestrator: FrontendOrchestratorKind(%s), DiagnosticsStream: DiagnosticsStream(%s), ",
			strconv.Quote(domain.frontendRefresherName),
			strconv.Quote(domain.frontendOrchestrator),
			strconv.Quote(domain.frontendDiagnosticsStream),
		)
		fmt.Fprintf(out, "Timing: FrontendTimingPolicy{Interval: %d, Cooldown: %d, Timeout: %d}, ",
			domain.frontendTimingInterval,
			domain.frontendTimingCooldown,
			domain.frontendTimingTimeout,
		)
		fmt.Fprintf(out, "Priority: %d, HasPriority: %t, RegistrationOrder: %d, Scheduled: %t}},\n",
			domain.frontendPriority,
			domain.frontendHasPriority,
			domain.frontendRegistrationOrder,
			domain.frontendScheduled,
		)
	}
	out.WriteString(`}

var authoredDomainPolicyByName = func() map[string]DomainPolicy {
	policies := make(map[string]DomainPolicy, len(authoredDomainPolicies))
	for _, policy := range authoredDomainPolicies {
		policies[policy.Domain] = policy
	}
	return policies
}()

func cloneDomainPolicy(policy DomainPolicy) DomainPolicy {
	policy.SourceClocks = append([]SourceClock(nil), policy.SourceClocks...)
	return policy
}

// Policies returns the authored refresh-domain policies in backend registration order.
func Policies() []DomainPolicy {
	policies := make([]DomainPolicy, len(authoredDomainPolicies))
	for index, policy := range authoredDomainPolicies {
		policies[index] = cloneDomainPolicy(policy)
	}
	return policies
}

// LookupPolicy returns one immutable copy of the authored policy for domainName.
func LookupPolicy(domainName string) (DomainPolicy, bool) {
	policy, ok := authoredDomainPolicyByName[domainName]
	return cloneDomainPolicy(policy), ok
}

// BypassesSnapshotCache reports whether the service-level snapshot cache must
// defer to live data or a domain-owned provider cache.
func BypassesSnapshotCache(domainName string) bool {
	policy, ok := authoredDomainPolicyByName[domainName]
	if !ok {
		return false
	}
	return policy.CachePolicy == CachePolicySnapshotCacheBypass ||
		policy.CachePolicy == CachePolicyProviderCache
}

// BypassesSingleflight reports whether concurrent snapshot requests must run
// independently because the domain exposes live operation state.
func BypassesSingleflight(domainName string) bool {
	policy, ok := authoredDomainPolicyByName[domainName]
	return ok && policy.Backend.BypassSingleflight
}
`)
}
