// Package genpreferences renders the frontend's app-preference contract from
// backend/internal/preferenceschema: the AppPreferences type, every key in
// declaration order, each preference's spec (type, default, bounds, allowed
// values, rules), the zoom bounds, and the color pattern. It also renders the
// parity vectors: boundary inputs with the schema's Repair result, which the
// frontend's normalizer must reproduce.
package genpreferences

import (
	"encoding/json"
	"fmt"
	"strings"

	"github.com/luxury-yacht/app/backend/internal/preferenceschema"
)

const generatedHeader = `// Code generated by genpreferences; DO NOT EDIT.
//
// backend/internal/preferenceschema is the source of truth.
// Regenerate with: go generate ./backend

export type AppPreferenceValueType = 'boolean' | 'integer' | 'enum' | 'string' | 'color';
export type AppPreferenceNonPositive = 'default' | 'clamp';
export type AppPreferenceValidation = 'dayjs-format' | '#rrggbb-or-empty';

export interface AppPreferenceSpec<K extends AppPreferenceKey = AppPreferenceKey> {
  readonly key: K;
  readonly type: AppPreferenceValueType;
  readonly defaultValue: AppPreferences[K];
  /** Range integers: bounds (max may be absent). */
  readonly min?: number;
  readonly max?: number;
  /** Enums: the allowed values. */
  readonly enumOptions?: readonly string[];
  /** Option-list integers: the allowed values, matched exactly. */
  readonly intOptions?: readonly number[];
  /** Range integers: what a value <= 0 means. */
  readonly nonPositive?: AppPreferenceNonPositive;
  readonly validation?: AppPreferenceValidation;
}

`

type specJSON struct {
	Key          string   `json:"key"`
	Type         string   `json:"type"`
	DefaultValue any      `json:"defaultValue"`
	Min          *int     `json:"min,omitempty"`
	Max          *int     `json:"max,omitempty"`
	EnumOptions  []string `json:"enumOptions,omitempty"`
	IntOptions   []int    `json:"intOptions,omitempty"`
	NonPositive  string   `json:"nonPositive,omitempty"`
	Validation   string   `json:"validation,omitempty"`
}

// Render generates the TypeScript contract.
func Render() ([]byte, error) {
	specs := preferenceschema.All()
	var out strings.Builder
	out.WriteString(generatedHeader)

	out.WriteString("export interface AppPreferences {\n")
	for _, spec := range specs {
		fmt.Fprintf(&out, "  %s: %s;\n", spec.Key, tsType(spec))
	}
	out.WriteString("}\n\nexport type AppPreferenceKey = keyof AppPreferences;\n\n")

	out.WriteString("/** Every key, in declaration order (the order subscribers are notified in). */\n")
	out.WriteString("export const APP_PREFERENCE_KEYS = [\n")
	for _, spec := range specs {
		fmt.Fprintf(&out, "  %q,\n", spec.Key)
	}
	out.WriteString("] as const satisfies readonly AppPreferenceKey[];\n\n")

	out.WriteString("export const APP_PREFERENCE_SPECS = {\n")
	for _, spec := range specs {
		encoded, err := json.Marshal(specRow(spec))
		if err != nil {
			return nil, fmt.Errorf("encode %s: %w", spec.Key, err)
		}
		fmt.Fprintf(&out, "  %s: %s,\n", spec.Key, encoded)
	}
	out.WriteString("} as const satisfies { readonly [K in AppPreferenceKey]: AppPreferenceSpec<K> };\n\n")

	out.WriteString("/** Zoom level bounds (percent). Zoom has its own commands, not an app preference. */\n")
	fmt.Fprintf(&out, "export const ZOOM_LEVEL = { defaultValue: %d, min: %d, max: %d } as const;\n\n",
		preferenceschema.DefaultZoomLevel, preferenceschema.MinZoomLevel, preferenceschema.MaxZoomLevel)
	out.WriteString("/** The #rrggbb form every color preference accepts. */\n")
	fmt.Fprintf(&out, "export const HEX_COLOR_PATTERN = %q;\n", preferenceschema.HexColorPattern)
	return []byte(out.String()), nil
}

func specRow(spec preferenceschema.Preference) specJSON {
	return specJSON{
		Key:          spec.Key,
		Type:         string(spec.Type),
		DefaultValue: spec.Default,
		Min:          spec.Min,
		Max:          spec.Max,
		EnumOptions:  spec.Options,
		IntOptions:   spec.IntOptions,
		NonPositive:  string(spec.NonPositive),
		Validation:   string(spec.Validation),
	}
}

func tsType(spec preferenceschema.Preference) string {
	switch spec.Type {
	case preferenceschema.Boolean:
		return "boolean"
	case preferenceschema.Enum:
		literals := make([]string, 0, len(spec.Options))
		for _, option := range spec.Options {
			literals = append(literals, "'"+option+"'")
		}
		return strings.Join(literals, " | ")
	case preferenceschema.Integer:
		if len(spec.IntOptions) == 0 {
			return "number"
		}
		literals := make([]string, 0, len(spec.IntOptions))
		for _, option := range spec.IntOptions {
			literals = append(literals, fmt.Sprint(option))
		}
		return strings.Join(literals, " | ")
	}
	return "string"
}

type parityVector struct {
	Key      string `json:"key"`
	Input    any    `json:"input"`
	Repaired any    `json:"repaired"`
}

type parityFile struct {
	GeneratedBy string         `json:"generatedBy"`
	Vectors     []parityVector `json:"vectors"`
}

// RenderParityVectors generates boundary inputs for every preference with the
// value the schema's Repair settles each one on.
func RenderParityVectors() ([]byte, error) {
	file := parityFile{GeneratedBy: "genpreferences; DO NOT EDIT. Regenerate with: go generate ./backend"}
	for _, spec := range preferenceschema.All() {
		for _, input := range vectorInputs(spec) {
			file.Vectors = append(file.Vectors, parityVector{Key: spec.Key, Input: input, Repaired: spec.Repair(input)})
		}
	}
	encoded, err := json.MarshalIndent(file, "", "  ")
	if err != nil {
		return nil, err
	}
	return append(encoded, '\n'), nil
}

// vectorInputs lists the inputs that exercise each of a preference's rules:
// missing and wrong-typed values for every type, plus the type's boundaries.
func vectorInputs(spec preferenceschema.Preference) []any {
	inputs := []any{nil}
	switch spec.Type {
	case preferenceschema.Boolean:
		inputs = append(inputs, true, false, "x")
	case preferenceschema.Integer:
		inputs = append(inputs, integerInputs(spec)...)
	case preferenceschema.Enum:
		for _, option := range spec.Options {
			inputs = append(inputs, option)
		}
		inputs = append(inputs, "unknown-option", "", 7)
	case preferenceschema.Color:
		inputs = append(inputs, "", "#a1B2c3", "#zzz", "blue", 7)
	case preferenceschema.String:
		// Only the cases both sides settle the same way: the frontend applies a
		// stricter Day.js check (preferenceschema.ValidationDayjsFormat).
		inputs = append(inputs, "", 7, spec.Default)
	}
	return dedupe(inputs)
}

func integerInputs(spec preferenceschema.Preference) []any {
	inputs := []any{0, -1, "x"}
	if len(spec.IntOptions) > 0 {
		for _, option := range spec.IntOptions {
			inputs = append(inputs, option)
		}
		last := spec.IntOptions[len(spec.IntOptions)-1]
		return append(inputs, 25.5, 100.5, 37, last+1)
	}
	lowest := *spec.Min
	inputs = append(inputs, lowest-1, lowest, float64(lowest)+0.5, 0.9, -0.5, -10.7)
	if spec.Max != nil {
		return append(inputs, *spec.Max, *spec.Max+1)
	}
	return append(inputs, 10_000_000)
}

func dedupe(inputs []any) []any {
	seen := map[string]bool{}
	unique := make([]any, 0, len(inputs))
	for _, input := range inputs {
		key := fmt.Sprintf("%T:%v", input, input)
		if !seen[key] {
			seen[key] = true
			unique = append(unique, input)
		}
	}
	return unique
}
