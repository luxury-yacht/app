// Package genkindfacets renders the frontend's per-kind facet table from the
// backend kind registry: one row per registered kind, with every facet the
// frontend decides behavior on (tabs, logs/shell/metrics sources, object-map
// support, and action eligibility). The frontend never lists kinds by hand.
package genkindfacets

import (
	"encoding/json"
	"fmt"
	"sort"
	"strings"

	"github.com/luxury-yacht/app/backend/internal/genappbindings"
	"github.com/luxury-yacht/app/backend/kind/kindregistry"
	"github.com/luxury-yacht/app/backend/kind/kindspec"
	"github.com/luxury-yacht/app/backend/resourcecontract"
)

const generatedHeader = `// Code generated by genkindfacets; DO NOT EDIT.
//
// The backend kind registry (backend/kind/kindregistry) is the source of truth.
// Regenerate with: go generate ./backend

import type { ObjectDetailType, RefreshDomain } from '@/core/refresh/types';

export type KindPanelPods = 'none' | 'owner' | 'node';
export type KindPanelLogs = 'none' | 'pod' | 'owned-pods' | 'node';
export type KindPanelShell = 'none' | 'exec' | 'node';
export type KindMetricsDomain = 'none' | 'pods' | 'namespace-workloads' | 'nodes';

export interface KindFacetsSchema {
  readonly group: string;
  readonly versions: readonly string[];
  readonly kind: string;
  readonly resource: string;
  readonly namespaced: boolean;
  readonly detailType: ObjectDetailType;
  readonly detailListsPods: boolean;
  readonly objectMap: boolean;
  readonly panel: {
    readonly pods: KindPanelPods;
    readonly jobs: boolean;
    readonly logs: KindPanelLogs;
    readonly shell: KindPanelShell;
    readonly debugContainer: boolean;
    readonly eventsTab: boolean;
    readonly yamlTab: boolean;
  };
  readonly metricsDomain: KindMetricsDomain;
  readonly listDomain: RefreshDomain | 'none';
  readonly display: {
    readonly shortName: string;
    readonly label: string;
    readonly searchAliases: readonly string[];
  };
  readonly actions: {
    readonly restart: boolean;
    readonly rollback: boolean;
    readonly scale: boolean;
    readonly portForward: boolean;
    readonly reconnect: boolean;
    readonly usesServicePortSpec: boolean;
    readonly trigger: boolean;
    readonly suspend: boolean;
    readonly cordon: boolean;
    readonly drain: boolean;
    readonly removeNamespaceFinalizer: boolean;
  };
}

export const GENERATED_KIND_FACETS = [
`

const generatedFooter = `] as const satisfies readonly KindFacetsSchema[];
`

// Row is one kind's facets as the frontend reads them. Every field is always
// written so an absent facet never reads as false.
type Row struct {
	Group           string   `json:"group"`
	Versions        []string `json:"versions"`
	Kind            string   `json:"kind"`
	Resource        string   `json:"resource"`
	Namespaced      bool     `json:"namespaced"`
	DetailType      string   `json:"detailType"`
	DetailListsPods bool     `json:"detailListsPods"`
	ObjectMap       bool     `json:"objectMap"`
	Panel           Panel    `json:"panel"`
	MetricsDomain   string   `json:"metricsDomain"`
	ListDomain      string   `json:"listDomain"`
	Display         Display  `json:"display"`
	Actions         Actions  `json:"actions"`
}

// Display is how the UI names the kind.
type Display struct {
	ShortName     string   `json:"shortName"`
	Label         string   `json:"label"`
	SearchAliases []string `json:"searchAliases"`
}

// Panel is the object panel's kind-dependent tabs.
type Panel struct {
	Pods           string `json:"pods"`
	Jobs           bool   `json:"jobs"`
	Logs           string `json:"logs"`
	Shell          string `json:"shell"`
	DebugContainer bool   `json:"debugContainer"`
	EventsTab      bool   `json:"eventsTab"`
	YAMLTab        bool   `json:"yamlTab"`
}

// Actions is the kind's object-action eligibility.
type Actions struct {
	Restart                  bool `json:"restart"`
	Rollback                 bool `json:"rollback"`
	Scale                    bool `json:"scale"`
	PortForward              bool `json:"portForward"`
	Reconnect                bool `json:"reconnect"`
	UsesServicePortSpec      bool `json:"usesServicePortSpec"`
	Trigger                  bool `json:"trigger"`
	Suspend                  bool `json:"suspend"`
	Cordon                   bool `json:"cordon"`
	Drain                    bool `json:"drain"`
	RemoveNamespaceFinalizer bool `json:"removeNamespaceFinalizer"`
}

var panelPods = map[kindspec.PanelPods]string{
	kindspec.PanelPodsNone: "none", kindspec.PanelPodsByOwner: "owner", kindspec.PanelPodsByNode: "node",
}

var panelShell = map[kindspec.PanelShell]string{
	kindspec.PanelShellNone: "none", kindspec.PanelShellExec: "exec", kindspec.PanelShellNode: "node",
}

var metricsDomains = map[kindspec.MetricsSource]string{
	kindspec.MetricsNone: "none", kindspec.MetricsPods: "pods",
	kindspec.MetricsWorkloads: "namespace-workloads", kindspec.MetricsNodes: "nodes",
}

// MetricsDomain is the refresh domain a metrics source reads ("none" for
// MetricsNone). The snapshot package's agreement test pins these names.
func MetricsDomain(source kindspec.MetricsSource) (string, bool) {
	domain, ok := metricsDomains[source]
	return domain, ok
}

func enumValue[T comparable](names map[T]string, value T, facet, kind string) (string, error) {
	name, ok := names[value]
	if !ok {
		return "", fmt.Errorf("%s: unknown %s value %v", kind, facet, value)
	}
	return name, nil
}

// servedVersions lists the identity contract's versions for a kind's group and
// kind, in contract order. The registry identity's own version must be among them.
func servedVersions(identity kindspec.Descriptor) ([]string, error) {
	versions := []string{}
	for _, resource := range resourcecontract.BuiltinResources {
		if resource.Group == identity.Identity.Group && resource.Kind == identity.Identity.Kind {
			versions = append(versions, resource.Version)
		}
	}
	for _, version := range versions {
		if version == identity.Identity.Version {
			return versions, nil
		}
	}
	return nil, fmt.Errorf("%s: identity version %s is not in the identity contract", identity.Identity.Kind, identity.Identity.Version)
}

func detailTypeTags() map[string]bool {
	tags := map[string]bool{}
	for _, detailType := range genappbindings.DetailTypes() {
		tags[detailType.Tag] = true
	}
	return tags
}

func actionsOf(descriptor kindspec.Descriptor) Actions {
	workload := descriptor.Workload
	actions := Actions{
		Restart:                  workload != nil && workload.Restart != nil,
		Rollback:                 workload != nil && workload.RevisionHistory != nil && workload.ApplyPodTemplate != nil,
		Scale:                    workload != nil && workload.Scale != nil,
		PortForward:              descriptor.PortForward != nil,
		Trigger:                  descriptor.Actions.Trigger,
		Suspend:                  descriptor.Actions.Suspend,
		Cordon:                   descriptor.Actions.Cordon,
		Drain:                    descriptor.Actions.Drain,
		RemoveNamespaceFinalizer: descriptor.Actions.NamespaceFinalizer,
	}
	if descriptor.PortForward != nil {
		actions.Reconnect = descriptor.PortForward.Reconnect
		actions.UsesServicePortSpec = descriptor.PortForward.UsesServicePortSpec
	}
	return actions
}

// logsSourceOf is the Logs tab's source: the node's own logs, one pod's
// containers, or the containers of the pods the object owns.
func logsSourceOf(descriptor kindspec.Descriptor) (string, error) {
	switch {
	case descriptor.Panel.NodeLogs && descriptor.Logs != nil:
		return "", fmt.Errorf("%s: declares both node logs and a container-log target", descriptor.Identity.Kind)
	case descriptor.Panel.NodeLogs:
		return "node", nil
	case descriptor.Logs == nil:
		return "none", nil
	case descriptor.Logs.SinglePod:
		return "pod", nil
	default:
		return "owned-pods", nil
	}
}

func panelOf(descriptor kindspec.Descriptor) (Panel, error) {
	kind := descriptor.Identity.Kind
	pods, err := enumValue(panelPods, descriptor.Panel.Pods, "panel pods", kind)
	if err != nil {
		return Panel{}, err
	}
	logs, err := logsSourceOf(descriptor)
	if err != nil {
		return Panel{}, err
	}
	shell, err := enumValue(panelShell, descriptor.Panel.Shell, "panel shell", kind)
	if err != nil {
		return Panel{}, err
	}
	return Panel{
		Pods: pods, Jobs: descriptor.Panel.Jobs, Logs: logs, Shell: shell,
		DebugContainer: descriptor.Panel.DebugContainer,
		EventsTab:      !descriptor.Panel.HideEvents,
		YAMLTab:        !descriptor.Panel.HideYAML,
	}, nil
}

func displayOf(descriptor kindspec.Descriptor) (Display, error) {
	display := descriptor.Display
	if display.ShortName == "" {
		return Display{}, fmt.Errorf("%s: no display short name", descriptor.Identity.Kind)
	}
	label := display.Label
	if label == "" {
		label = descriptor.Identity.Kind
	}
	return Display{
		ShortName: display.ShortName, Label: label,
		SearchAliases: append([]string{}, display.SearchAliases...),
	}, nil
}

// listDomainOf is the domain whose table lists the kind: its stream descriptor's
// domain, or the domain a bespoke kind declares. Declaring both is an error.
func listDomainOf(descriptor kindspec.Descriptor) (string, error) {
	if descriptor.Stream != nil {
		if descriptor.ListDomain != "" {
			return "", fmt.Errorf("%s: ListDomain is set but its stream descriptor names the domain", descriptor.Identity.Kind)
		}
		return descriptor.Stream.Domain, nil
	}
	if descriptor.ListDomain == "" {
		return "none", nil
	}
	return descriptor.ListDomain, nil
}

func rowOf(descriptor kindspec.Descriptor, detailTypes map[string]bool) (Row, error) {
	identity := descriptor.Identity
	detailType := strings.ToLower(identity.Kind)
	if !detailTypes[detailType] {
		return Row{}, fmt.Errorf("%s: no generated detail type %q", identity.Kind, detailType)
	}
	versions, err := servedVersions(descriptor)
	if err != nil {
		return Row{}, err
	}
	panel, err := panelOf(descriptor)
	if err != nil {
		return Row{}, err
	}
	metrics, err := enumValue(metricsDomains, descriptor.Metrics, "metrics source", identity.Kind)
	if err != nil {
		return Row{}, err
	}
	display, err := displayOf(descriptor)
	if err != nil {
		return Row{}, err
	}
	listDomain, err := listDomainOf(descriptor)
	if err != nil {
		return Row{}, err
	}
	return Row{
		Group: identity.Group, Versions: versions, Kind: identity.Kind, Resource: identity.Resource,
		Namespaced: identity.Namespaced, DetailType: detailType,
		DetailListsPods: descriptor.DetailListsPods, ObjectMap: descriptor.Collector != nil,
		Panel: panel, MetricsDomain: metrics, ListDomain: listDomain, Display: display,
		Actions: actionsOf(descriptor),
	}, nil
}

// Rows builds one facet row per registered kind, sorted by kind.
func Rows() ([]Row, error) {
	detailTypes := detailTypeTags()
	rows := make([]Row, 0, len(kindregistry.All))
	for _, descriptor := range kindregistry.All {
		row, err := rowOf(descriptor, detailTypes)
		if err != nil {
			return nil, err
		}
		rows = append(rows, row)
	}
	sort.Slice(rows, func(i, j int) bool { return rows[i].Kind < rows[j].Kind })
	return rows, nil
}

// Render generates the TypeScript facet table: a structural schema plus the
// rows as one literal, checked against the schema and kept as literal types.
func Render() ([]byte, error) {
	rows, err := Rows()
	if err != nil {
		return nil, err
	}
	var out strings.Builder
	out.WriteString(generatedHeader)
	for _, row := range rows {
		encoded, err := json.Marshal(row)
		if err != nil {
			return nil, err
		}
		out.WriteString("  ")
		out.Write(encoded)
		out.WriteString(",\n")
	}
	out.WriteString(generatedFooter)
	return []byte(out.String()), nil
}
